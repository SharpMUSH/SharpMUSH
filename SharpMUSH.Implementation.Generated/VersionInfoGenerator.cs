using Microsoft.CodeAnalysis;

namespace SharpMUSH.Implementation.Generated;

/// <summary>
/// Emits <c>VersionInfo</c> from the <c>SharpMUSHVersion</c> MSBuild property (Directory.Build.props, or
/// <c>-p:SharpMUSHVersion=</c> from the release tag). This is the engine's version, apart from the plugin
/// contract version this generator's own package carries.
/// </summary>
[Generator]
public class VersionInfoGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var version = context.AnalyzerConfigOptionsProvider.Select((options, _) =>
			options.GlobalOptions.TryGetValue("build_property.SharpMUSHVersion", out var value) && !string.IsNullOrWhiteSpace(value)
				? value.Trim()
				: "0.0.0");

		context.RegisterSourceOutput(version, Execute);
	}

	private static void Execute(SourceProductionContext context, string version)
	{
		var code = $$"""
		             // <autogenerated/>
		             namespace SharpMUSH.Implementation.Generated;

		             public static class VersionInfo
		             {
		                 public const string SharpMUSHVersion = "{{version}}";
		                 public const string Version = "PennMUSH emulated in SharpMUSH " + SharpMUSHVersion;
		             }
		             """;

		context.AddSource("VersionInfo.g.cs", code);
	}
}
