using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Globalization;
using System.Collections.Immutable;
using System.Linq;

namespace SharpMUSH.Configuration.Generated;

[Generator]
public class ConfigAccessorGenerator : IIncrementalGenerator
{
	private const string SHARPATTRIBUTE = "SharpConfigAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var optionsProvider = context.SyntaxProvider
			.CreateSyntaxProvider(
				predicate: static (s, _) => s is RecordDeclarationSyntax { Identifier.Text: "SharpMUSHOptions" },
				transform: static (ctx, _) => (RecordDeclarationSyntax)ctx.Node)
			.Where(static m => m is not null);

		var compilation = context.CompilationProvider.Combine(optionsProvider.Collect());

		context.RegisterSourceOutput(compilation, Execute);
	}

	private static void Execute(SourceProductionContext spc,
		(Compilation Left, ImmutableArray<RecordDeclarationSyntax> Right) arg)
	{
		var compilation = arg.Left;
		var optionsClasses = arg.Right;

		if (optionsClasses.Length == 0) return;

		var optionsClass = optionsClasses[0];
		var semanticModel = compilation.GetSemanticModel(optionsClass.SyntaxTree);
		var optionsSymbol = semanticModel.GetDeclaredSymbol(optionsClass) as INamedTypeSymbol;

		if (optionsSymbol == null) return;

		var categories = SelectCategoryProperties(optionsSymbol).ToImmutableArray();
		var allProperties = categories
			.SelectMany(cat => SelectConfigProperties(cat).Select(prop => (Category: cat, Property: prop)))
			.ToImmutableArray();

		var categoriesList = string.Join(",\n            ", categories.Select(c => $"\"{c.Name}\""));

		var str = $$"""
		            // <autogenerated/>
		            #nullable enable
		            using System;
		            using System.Collections.Generic;
		            using System.Collections.Immutable;
		            using SharpMUSH.Configuration.Options;
		            
		            namespace SharpMUSH.Configuration.Generated;
		            
		            public static class ConfigAccessor
		            {
		                public static readonly ImmutableArray<string> Categories = [
		                    {{categoriesList}}
		                ];
		                
		                public static object? GetValue(SharpMUSHOptions options, string propertyName)
		                {
		                    return propertyName switch
		                    {
		                        {{string.Join("\n                ", allProperties.Select(p => $"\"{p.Property.Name}\" => options.{p.Category.Name}.{p.Property.Name},"))}}
		                        _ => null
		                    };
		                }
		                
		                public static bool TryGetValue(SharpMUSHOptions options, string propertyName, out object? value)
		                {
		                    value = GetValue(options, propertyName);
		                    return value != null;
		                }
		                
		                public static Type? GetPropertyType(string propertyName)
		                {
		                    return propertyName switch
		                    {
		                        {{string.Join("\n                ", allProperties.Select(p => $"\"{p.Property.Name}\" => typeof({GetTypeName(p.Property.Type)}),"))}}
		                        _ => null
		                    };
		                }
		                
		                public static string? GetCategoryForProperty(string propertyName)
		                {
		                    return propertyName switch
		                    {
		                        {{string.Join("\n                ", allProperties.Select(p => $"\"{p.Property.Name}\" => \"{p.Category.Name}\","))}}
		                        _ => null
		                    };
		                }
		                
		                /// <summary>The default declared on the property's primary-constructor parameter, or null when it declares none.</summary>
		                public static object? GetDeclaredDefault(string propertyName)
		                {
		                    return propertyName switch
		                    {
		                        {{string.Join("\n                ", allProperties.Select(p => $"\"{p.Property.Name}\" => {DeclaredDefault(p.Category, p.Property)},"))}}
		                        _ => null
		                    };
		                }
		                
		                private static readonly ImmutableDictionary<string, string> CanonicalPropertyNames =
		                    new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
		                    {
		                        {{string.Join("\n                ", allProperties.Select(p => $"{{ \"{p.Property.Name}\", \"{p.Property.Name}\" }},"))}}
		                    }.ToImmutableDictionary(StringComparer.OrdinalIgnoreCase);
		                
		                private static readonly ImmutableDictionary<string, string> CanonicalCategoryNames =
		                    new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
		                    {
		                        {{string.Join("\n                ", categories.Select(c => $"{{ \"{c.Name}\", \"{c.Name}\" }},"))}}
		                    }.ToImmutableDictionary(StringComparer.OrdinalIgnoreCase);
		                
		                /// <summary>Canonical casing for a property name, or null when no such property exists.</summary>
		                public static string? ResolvePropertyName(string propertyName)
		                    => CanonicalPropertyNames.TryGetValue(propertyName, out var canonical) ? canonical : null;
		                
		                /// <summary>Canonical casing for a category name, or null when no such category exists.</summary>
		                public static string? ResolveCategoryName(string categoryName)
		                    => CanonicalCategoryNames.TryGetValue(categoryName, out var canonical) ? canonical : null;
		                
		                /// <summary>
		                /// Returns a copy of <paramref name="options"/> with one property replaced, rebuilding only the
		                /// records on the path to it. <paramref name="propertyName"/> must be canonical — resolve it with
		                /// <see cref="ResolvePropertyName"/> first.
		                /// </summary>
		                public static SharpMUSHOptions WithValue(SharpMUSHOptions options, string propertyName, object? value)
		                {
		                    return propertyName switch
		                    {
		                        {{string.Join("\n                ", allProperties.Select(WithValueArm))}}
		                        _ => throw new ArgumentOutOfRangeException(nameof(propertyName), propertyName,
		                            "Not a configured property.")
		                    };
		                }
		                
		            }
		            """;

		spc.AddSource("ConfigAccessor_Generated.g.cs", str);
	}

	private static string WithValueArm((IPropertySymbol Category, IPropertySymbol Property) p)
	{
		var category = p.Category.Name;
		var property = p.Property.Name;
		var type = GetTypeName(p.Property.Type);

		return $"\"{property}\" => options with {{ {category} = options.{category} with {{ {property} = ({type})value! }} }},";
	}

	private static IParameterSymbol? PrimaryConstructorParameter(IPropertySymbol category, IPropertySymbol property)
		=> category.Type is not INamedTypeSymbol categoryType
			? null
			: categoryType.Constructors
				.OrderByDescending(c => c.Parameters.Length)
				.FirstOrDefault()
				?.Parameters
				.FirstOrDefault(param => param.Name == property.Name);

	private static string DeclaredDefault(IPropertySymbol category, IPropertySymbol property)
	{
		var parameter = PrimaryConstructorParameter(category, property);

		return parameter is { HasExplicitDefaultValue: true }
			? Literal(parameter.ExplicitDefaultValue)
			: "null";
	}

	/// <summary>
	/// Re-emits a boxed constant with its own type. GetDeclaredDefault is typed object?, so a uint default
	/// written as a bare number would come back an int and compare unequal to the property's real value.
	/// </summary>
	private static string Literal(object? value) => value switch
	{
		null => "null",
		bool b => b ? "true" : "false",
		string str => $"\"{EscapeString(str)}\"",
		char c => $"'{(c == '\'' ? "\\'" : c == '\\' ? "\\\\" : c.ToString())}'",
		int i => i.ToString(CultureInfo.InvariantCulture),
		uint u => u.ToString(CultureInfo.InvariantCulture) + "u",
		long l => l.ToString(CultureInfo.InvariantCulture) + "L",
		ulong ul => ul.ToString(CultureInfo.InvariantCulture) + "UL",
		short sh => "(short)" + sh.ToString(CultureInfo.InvariantCulture),
		ushort us => "(ushort)" + us.ToString(CultureInfo.InvariantCulture),
		double d => d.ToString("R", CultureInfo.InvariantCulture) + "d",
		float f => f.ToString("R", CultureInfo.InvariantCulture) + "f",
		decimal m => m.ToString(CultureInfo.InvariantCulture) + "m",
		_ => "null"
	};

	private static string EscapeString(string str)
		=> str.Replace("\\", "\\\\").Replace("\"", "\\\"");

	private static string GetTypeName(ITypeSymbol type)
	{
		return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
	}

	private static IEnumerable<IPropertySymbol> SelectCategoryProperties(INamedTypeSymbol optionsSymbol)
		=> optionsSymbol.GetMembers().OfType<IPropertySymbol>().Where(x => x.Name is not "EqualityContract");

	private static IEnumerable<IPropertySymbol> SelectConfigProperties(IPropertySymbol category)
	{
		return category.Type is INamedTypeSymbol categoryType
			? categoryType
				.GetMembers()
				.OfType<IPropertySymbol>()
				.Where(p => p.GetAttributes().Any(a => a.AttributeClass?.Name == SHARPATTRIBUTE))
			: [];
	}
}
