#!/usr/bin/env python3
"""Writes SharpMUSH.Client/Components/Map/MapIcons.cs from icons.txt and the game-icons.net archive.

    curl -sSLO https://game-icons.net/archives/svg/zip/000000/transparent/game-icons.net.svg.zip
    unzip -q game-icons.net.svg.zip -d game-icons
    python3 tools/map-icons/generate.py game-icons

The icons are CC BY 3.0: every author whose icon ships is credited where the portal shows them.
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "SharpMUSH.Client", "Components", "Map", "MapIcons.cs")

# How each author folder of the archive names its author, as the archive's license.txt does.
AUTHORS = {
	"lorc": "Lorc",
	"delapouite": "Delapouite",
	"caro-asercion": "Caro Asercion",
	"sbed": "Sbed",
	"skoll": "Skoll",
	"cathelineau": "Cathelineau",
	"pepijn-poolman": "Pepijn Poolman",
}


def picks():
	for line in open(os.path.join(HERE, "icons.txt"), encoding="utf-8"):
		line = line.strip()
		if not line or line.startswith("#"):
			continue
		name, _, source = line.partition("=")
		source = source or name
		icon, _, author = source.partition("@")
		yield name, icon, author


def main(archive):
	entries = []
	for name, icon, author in picks():
		found = sorted(glob.glob(os.path.join(archive, "**", "000000", "transparent", "1x1", author or "*", icon + ".svg"), recursive=True))
		if not found:
			sys.exit(f"{icon}: not in the archive")
		if len(found) > 1 and not author:
			sys.exit(f"{icon}: by more than one author, name one: {', '.join(p.split(os.sep)[-2] for p in found)}")
		folder = found[0].split(os.sep)[-2]
		if folder not in AUTHORS:
			sys.exit(f"{folder}: add the author's name to AUTHORS")
		paths = re.findall(r'<path[^>]*?\sd="([^"]+)"', open(found[0], encoding="utf-8").read())
		if len(paths) != 1:
			sys.exit(f"{icon}: expected one path, found {len(paths)}")
		entries.append((name, paths[0], AUTHORS[folder]))

	with open(OUT, "w", encoding="utf-8", newline="\n") as out:
		out.write("// <auto-generated>\n// Written by tools/map-icons/generate.py from tools/map-icons/icons.txt. Do not edit by hand.\n// </auto-generated>\n")
		out.write("namespace SharpMUSH.Client.Components.Map;\n\n")
		out.write("/// <summary>\n/// The map icons, from game-icons.net (CC BY 3.0), each scaled from its 512-unit square into MudBlazor's 24, with\n/// the author it is credited to.\n/// </summary>\n")
		out.write("public static class MapIcons\n{\n")
		out.write("\tpublic static readonly IReadOnlyDictionary<string, (string Svg, string Author)> All =\n")
		out.write("\t\tnew Dictionary<string, (string Svg, string Author)>(StringComparer.OrdinalIgnoreCase)\n\t\t{\n")
		for name, path, author in entries:
			out.write(f'\t\t\t["{name}"] = ("<g transform=\\"scale(0.046875)\\"><path d=\\"{path}\\"/></g>", "{author}"),\n')
		out.write("\t\t};\n}\n")
	print(f"Wrote {len(entries)} icons to {os.path.normpath(OUT)}")


if __name__ == "__main__":
	main(sys.argv[1] if len(sys.argv) > 1 else "game-icons")
