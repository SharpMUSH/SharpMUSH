#!/usr/bin/env python3
"""Writes SharpMUSH.Library/Softcode/DialectSwitchNames.cs: each command's switch names, in table order and with
the shortest start each takes, as RhostMUSH and TinyMUX list them. Only the names and lengths are read.

Usage: generate.py <RhostMUSH Server/src/command.c> <TinyMUX mux/modules/engine/command.cpp> <output .cs>
"""
import re
import sys

ENTRY = re.compile(r'\{\s*(?:\(char \*\)\s*|T\()?\s*"([^"]+)"\)?\s*,\s*(\d+)\s*,')
COMMAND = re.compile(r'\{\s*(?:\(char \*\)\s*|T\()\s*"([^"]+)"\)?\s*,\s*(\w+)\s*,')
TABLE = re.compile(r'NAMETAB\s+(\w+)\[\]\s*=\s*\{(.*?)\};', re.S)


def read(path):
	source = open(path, encoding='latin-1').read()
	tables = {name: [(m.group(1), int(m.group(2))) for m in ENTRY.finditer(body)]
		for name, body in TABLE.findall(source)}
	commands = {}
	for m in COMMAND.finditer(source):
		name, table = m.group(1).lower(), m.group(2)
		if tables.get(table):
			commands.setdefault(name, tables[table])
	return dict(sorted(commands.items()))


def emit(name, commands):
	lines = [f'\tpublic static readonly IReadOnlyDictionary<string, DialectSwitchName[]> {name} =',
		'\t\tnew Dictionary<string, DialectSwitchName[]>(StringComparer.OrdinalIgnoreCase)', '\t\t{']
	items = list(commands.items())
	for index, (command, switches) in enumerate(items):
		names = ', '.join(f'new("{switch}", {length})' for switch, length in switches)
		comma = ',' if index < len(items) - 1 else ''
		lines.append(f'\t\t\t["{command}"] = [{names}]{comma}')
	lines.append('\t\t};')
	return lines


def main():
	rhost, mux, output = sys.argv[1:4]
	lines = ['// <auto-generated>tools/dialect-switches/generate.py</auto-generated>', '',
		'namespace SharpMUSH.Library.Softcode;', '',
		'/// <summary>', "/// Each command's switch names on RhostMUSH and TinyMUX, in the order the server tries them, with the shortest",
		'/// start each one takes.', '/// </summary>',
		'internal static class DialectSwitchNames', '{']
	lines += emit('Rhost', read(rhost)) + [''] + emit('Mux', read(mux)) + ['}', '']
	open(output, 'w', newline='\n').write('\n'.join(lines))


main()
